"""Add the Tezera document navbar to the generated architecture page.

prd/tezera-architecture.html is generated by archify `finalize`, which drops
anything added by hand. Run this after copying a new finalize output into
prd/:

    python3 .archify/inject-nav.py

Safe to run more than once: an existing navbar is replaced, not duplicated.
"""
import pathlib
import re

PAGE = pathlib.Path(__file__).resolve().parent.parent / "prd" / "tezera-architecture.html"

STYLE = """<style id="tezera-docnav-style">
    #tezera-docnav { display: flex; align-items: center; gap: 12px 20px; flex-wrap: wrap; min-height: 2.75rem; margin: 0 0 1.25rem; padding-right: 26rem; }
    #tezera-docnav .wordmark { font-family: "Bricolage Grotesque", Georgia, serif; font-weight: 600; font-size: 24px; letter-spacing: -.02em; color: var(--text); text-decoration: none; display: inline-flex; align-items: center; }
    #tezera-docnav .wordmark .dot { width: 11px; height: 11px; border-radius: 50%; background: #E3A21A; box-shadow: 13px 0 0 #1F6F78; margin-right: 24px; }
    #tezera-docnav .doclinks { display: flex; gap: 6px; flex-wrap: wrap; font-size: 14px; }
    #tezera-docnav .doclinks a { padding: 5px 12px; border: 1px solid var(--panel-border); border-radius: 999px; color: var(--text-muted); text-decoration: none; background: var(--panel); }
    #tezera-docnav .doclinks a:hover { color: var(--text); }
    #tezera-docnav .doclinks a[aria-current] { background: var(--text); color: var(--bg); border-color: var(--text); }
    @media (max-width: 1100px) { #tezera-docnav { padding-right: 0; margin-top: 3.25rem; } }
    @media (max-width: 720px) { #tezera-docnav { margin-top: 0; margin-bottom: .75rem; } }
    html[data-embed="true"] #tezera-docnav, html[data-present="true"] #tezera-docnav { display: none !important; }
    @media print { #tezera-docnav { display: none !important; } }
  </style>
"""

NAV = """<nav id="tezera-docnav" aria-label="Tezera documents">
    <a class="wordmark" href="tezera-prd.html"><span class="dot" aria-hidden="true"></span>tezera</a>
    <div class="doclinks">
      <a href="tezera-prd.html">PRD</a>
      <a href="tezera-architecture.html" aria-current="page">Architecture</a>
      <a href="../research/tezera-survey-analysis.html">Survey analysis</a>
      <a href="../research/tezera-user-stories.html">User stories</a>
    </div>
  </nav>
"""

html = PAGE.read_text(encoding="utf-8")
html = re.sub(r'<style id="tezera-docnav-style">.*?</style>\n', "", html, flags=re.S)
html = re.sub(r'<nav id="tezera-docnav".*?</nav>\n', "", html, flags=re.S)
assert html.count("</head>") == 1 and html.count("<body>") == 1, "unexpected page structure"
html = html.replace("</head>", "  " + STYLE + "</head>", 1)
html = html.replace("<body>\n", "<body>\n  " + NAV, 1)
PAGE.write_text(html, encoding="utf-8", newline="")
print("navbar injected into", PAGE)
